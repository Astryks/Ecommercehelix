"""Build src/lib/daily-topics.json: one topic a day for the daily email, Instagram and the members' Facebook group.
Source: Helix's own lessons in docs/playbook (already in Helix wording). Ordered by the framework: Attract, then Convert, then Grow.
Run: python3 scripts/build_daily_topics.py"""
import json, re, os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PB = os.path.join(ROOT, "docs", "playbook")
smap = json.load(open(os.path.join(ROOT, "src/lib/stage-map.json")))
stage = lambda ref: smap["lessons"].get(ref) or smap["modules"].get(ref.split(".")[0], "grow")
BANNED = re.compile(r"skool|ecommerce equation|black belt|\bnsw\b|sydney|astryks|lawyer|real brand", re.I)
def slug(t): return re.sub(r"\s", "-", re.sub(r"[^\w\s-]", "", re.sub(r"<[^>]+>", "", t.lower().strip())))
def clean(s):
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s); s = re.sub(r"\*\*|`|<!--.*?-->", "", s)
    s = re.sub(r"\s*\((see )?Lessons? [\d., and]+\)", "", s)
    return re.sub(r"\s+", " ", s).strip()
def first_sentence(s):
    m = re.match(r"(.+?[.!?])(\s|$)", s); return m.group(1) if m else s
lessons = []
for f in sorted(os.listdir(PB)):
    if not re.match(r"^\d\d-.*\.md$", f): continue
    md = open(os.path.join(PB, f)).read()
    for part in re.split(r"^(?=## )", md, flags=re.M)[1:]:
        head = part.splitlines()[0][3:].strip()
        m = re.match(r"Lesson (\d+\.\d+):\s*(.+)", head)
        if not m: continue
        ref, title = m.group(1), m.group(2).strip()
        why = re.search(r"\*\*Why this matters:\*\*\s*(.+)", part)
        steps = [clean(s) for s in re.findall(r"^\*\*Step \d+\.\*\*\s*(.+)$", part, re.M)]
        results = [clean(s) for s in re.findall(r"^\*\*Expected result:\*\*\s*(.+)$", part, re.M)]
        if not why or len(steps) < 3: continue
        w = clean(why.group(1))
        if BANNED.search(title + w + " ".join(steps)): continue
        lessons.append(dict(ref=ref, title=title, stage=stage(ref), why=w, steps=steps[:6], results=results[:6],
                            href=f"/learn/{f[:-3]}#{slug(head)}", module=int(ref.split('.')[0])))
PER = 24
out = []
for st in ["attract", "convert", "grow"]:
    pool = [l for l in lessons if l["stage"] == st]
    by = collections.defaultdict(list)
    for l in pool: by[l["module"]].append(l)
    # Round-robin across modules so each stage block covers many chapters, keeping module order.
    picked, i = [], 0
    while len(picked) < PER and any(by.values()):
        for mod in sorted(by):
            if by[mod] and len(picked) < PER: picked.append(by[mod].pop(0))
    picked.sort(key=lambda l: (l["module"], [int(x) for x in l["ref"].split(".")]))
    out += picked
for n, t in enumerate(out, 1): t["n"] = n
json.dump({"_note": "Generated by scripts/build_daily_topics.py. One topic per day, same for email, Instagram and the Facebook group. Cycle = len(topics) days, no repeats inside a cycle.", "topics": out}, open(os.path.join(ROOT, "src/lib/daily-topics.json"), "w"), indent=1)
print(len(out), collections.Counter(t["stage"] for t in out))
