"""Draws the E-commerce Helix mark: a sketchy double helix rising to the right, one purple strand and one ink strand.

Writes src/components/logo-paths.ts, src/app/icon.svg, public/logo.svg, the PNG icons and favicon.ico.
Usage: python3 scripts/build_logo.py
"""
import math, random, io
from pathlib import Path
import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PURPLE, INK, PAPER = "#6258DF", "#1A1718", "#F2F1EC"
random.seed(7)

def pt(x, y):  # rotate -40 degrees around the centre so the helix rises to the right
    a = math.radians(-40); cx = cy = 256
    x, y = x - 256, y - 256
    return cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)

def strand(phase, jitter):
    pts = []
    for i in range(0, 61):
        t = i / 60
        x = 60 + t * 392
        y = 256 + 78 * math.sin(t * 2.5 * math.pi + phase) + random.uniform(-jitter, jitter)
        pts.append(pt(x, y))
    d = f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    for a, b in zip(pts[1::2], pts[2::2]):
        d += f" Q{a[0]:.1f},{a[1]:.1f} {b[0]:.1f},{b[1]:.1f}"
    return d

def rungs():
    out = []
    for i in range(1, 12):
        t = i / 12
        x = 60 + t * 392
        y1 = 256 + 78 * math.sin(t * 2.5 * math.pi)
        y2 = 256 + 78 * math.sin(t * 2.5 * math.pi + math.pi)
        if abs(y1 - y2) < 40: continue
        a, b = pt(x + random.uniform(-3, 3), y1), pt(x + random.uniform(-3, 3), y2)
        out.append(f"M{a[0]:.1f},{a[1]:.1f} L{b[0]:.1f},{b[1]:.1f}")
    return " ".join(out)

INK_A, INK_B = strand(math.pi, 2.5), strand(math.pi + 0.05, 3.5)
PUR_A, PUR_B = strand(0, 2.5), strand(0.05, 3.5)
RUNGS = rungs()

def svg(bg=None, rx=0):
    rect = f'<rect width="512" height="512" rx="{rx}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">{rect}'
            f'<g fill="none" stroke-linecap="round" stroke-linejoin="round">'
            f'<path d="{RUNGS}" stroke="{INK}" stroke-width="9" opacity="0.85"/>'
            f'<path d="{INK_A}" stroke="{INK}" stroke-width="26"/><path d="{INK_B}" stroke="{INK}" stroke-width="7" opacity="0.6"/>'
            f'<path d="{PUR_A}" stroke="{PURPLE}" stroke-width="30"/><path d="{PUR_B}" stroke="{PURPLE}" stroke-width="8" opacity="0.55"/>'
            f'</g></svg>')

(ROOT / "src/components/logo-paths.ts").write_text(
    "// Generated by scripts/build_logo.py. Do not edit by hand.\n"
    + "".join(f'export const {k} = "{v}";\n' for k, v in [("INK_A", INK_A), ("INK_B", INK_B), ("PUR_A", PUR_A), ("PUR_B", PUR_B), ("RUNGS", RUNGS)]))
(ROOT / "src/app/icon.svg").write_text(svg(PAPER, 96))
(ROOT / "public/logo.svg").write_text(svg(PAPER, 0))

def png(size, rx=96):
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg(PAPER, rx).encode(), output_width=size, output_height=size))).convert("RGBA")
png(192).save(ROOT / "public/icon-192.png")
png(512).save(ROOT / "public/icon-512.png")
png(180, 0).save(ROOT / "src/app/apple-icon.png")
png(256).save(ROOT / "src/app/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64)])
print("ok")
